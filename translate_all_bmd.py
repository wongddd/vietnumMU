def xor_transform(data, length=None):
    if length is None:
        length = len(data)
    result = bytearray(data)
    lim = min(length, len(result))
    for i in range(lim):
        result[i] ^= KEY[i % 3]
    return bytes(result)

def decode_bmd_bytes(data):
    """Try to decode bytes as UTF-8 then GBK, return (str, encoding)"""
    for enc in ('utf-8', 'gbk'):
        try:
            s = data.decode(enc)
            if '�' not in s:
                return s, enc
        except:
            pass
    return data.decode('utf-8', errors='replace'), 'utf-8'

def find_strings(data, min_len=3):
    strings = []
    start = -1
    for i in range(len(data)):
        b = data[i]
        if b >= 0x20 and b != 0x7F:
            if start == -1:
                start = i
        else:
            if start != -1 and i - start >= min_len:
                raw = bytes(data[start:i])
                s, _ = decode_bmd_bytes(raw)
                if any(c.isalnum() or ord(c) > 0x80 for c in s):
                    strings.append((start, i, s))
            start = -1
    if start != -1 and len(data) - start >= min_len:
        raw = bytes(data[start:])
        s, _ = decode_bmd_bytes(raw)
        if any(c.isalnum() or ord(c) > 0x80 for c in s):
            strings.append((start, len(data), s))
    return strings

def translate_string(s):
    """Translate VN/EN string to Chinese using dictionary (case-insensitive matching)"""
    result = s
    for pattern, replacement in compiled_patterns:
        result = pattern.sub(replacement, result)
    return result

def has_vn_chars(s):
    return bool(re.search(r'[àáạãăèéẹẽêìíịĩòóọõôơùúụũưừừửữựđ]', s))

def has_only_ascii(s):
    return all(0x20 <= ord(c) <= 0x7E for c in s)

def count_vn_lines(lines):
    """Count lines with VN text"""
    count = 0
    for line in lines:
        # Extract text between quotes
        qs = line.find('"')
        qe = line.rfind('"')
        if qs != -1 and qe > qs:
            text = line[qs+1:qe]
            if has_vn_chars(text):
                count += 1
    return count

