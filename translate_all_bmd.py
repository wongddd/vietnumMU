def rebuild_item_bmd(bmd_path):
    """Translate Item_CHN.bmd using Item.txt + custom translations"""
    name = os.path.basename(bmd_path)
    print(f'\n[{name}]')

    cn_names = {}
    with open(ITEM_TXT, 'r', encoding='utf-8') as f:
        lines = f.readlines()
    ct, si, ins = -1, 0, False
    for line in lines:
        ls = line.strip()
        if not ls or ls.startswith('//'): continue
        if ls == 'end': ins = False; si = 0; continue
        if ls.isdigit(): ct = int(ls); ins = True; si = 0; continue
        if not ins: continue
        parts = ls.split('\t')
        if len(parts) >= 9:
            m = re.search(r'"([^"]*)"', parts[8])
            if m and m.group(1).strip():
                flat = ct * 512 + si
                if flat < 8192: cn_names[flat] = m.group(1).strip()
        si += 1

    with open(bmd_path, 'rb') as f:
        raw = f.read()
    data_end = min(84 * 8192, len(raw))
    decrypted = bytearray(xor_transform(raw, data_end))

    cn_count = 0
    custom_count = 0
    for idx in range(8192):
        offset = idx * 84
        if offset + 30 > data_end: break
        nb = bytes(decrypted[offset:offset+30])
        null_pos = nb.find(b'\x00')
        if null_pos == -1: null_pos = 30

        name_to_write = None
        if idx in cn_names:
            name_to_write = cn_names[idx]
            cn_count += 1
        elif null_pos > 0:
            current_name = nb[:null_pos].decode('utf-8', errors='replace')
            translated = translate_string(current_name)
            if translated != current_name:
                name_to_write = translated
                custom_count += 1

        if name_to_write:
            encoded = name_to_write.encode('gbk', errors='replace')
            max_len = min(len(encoded), 29)
            decrypted[offset:offset+max_len] = encoded[:max_len]
            if max_len < 30:
                decrypted[offset+max_len:offset+30] = b'\x00' * (30 - max_len)

    encrypted = xor_transform(bytes(decrypted), data_end)
    with open(bmd_path, 'wb') as f:
        f.write(encrypted)
        if len(raw) > data_end:
            f.write(raw[data_end:])
    print(f'  Item.txt: {cn_count} | Custom: {custom_count}')


def translate_text_txt_format(txt_path):
    """Translate a TXT file in format: index \"text\" or index\\tnumber\\t\"text\""""
    name = os.path.basename(txt_path)
    print(f'\n[{name}]')

    # Read with encoding detection
    with open(txt_path, 'rb') as f:
        raw = f.read()

    binary_lines = raw.split(b'\n')
    lines = []
    for bl in binary_lines:
        bl = bl.rstrip(b'\r')
        try:
            lines.append(bl.decode('utf-8'))
        except:
            try:
                lines.append(bl.decode('gbk'))
            except:
                lines.append(bl.decode('latin-1'))

    # Count VN lines
    vn_total = count_vn_lines(lines)
    translated = 0
    new_lines = []

    for line in lines:
        qs = line.find('"')
        qe = line.rfind('"')
        if qs != -1 and qe > qs:
            prefix = line[:qs+1]
            suffix = line[qe:]
            text = line[qs+1:qe]
            new_text = translate_string(text)
            if new_text != text:
                translated += 1
            new_lines.append(f'{prefix}{new_text}{suffix}\n')
        else:
            new_lines.append(line + '\n')

    # Write back
    with open(txt_path, 'w', encoding='utf-8') as f:
        f.writelines(new_lines)
    print(f'  VN lines: {vn_total} | Translated: {translated}')


def patch_bmd_from_txt(bmd_path, txt_path):
    """Apply translations from TXT file to corresponding BMD file"""
    name = os.path.basename(bmd_path)
    print(f'  BMD patch: {name}')

    # Read TXT to get all translated strings by position
    txt_translations = {}
    with open(txt_path, 'r', encoding='utf-8') as f:
        txt_lines = f.readlines()

    for line in txt_lines:
        qs = line.find('"')
        qe = line.rfind('"')
        if qs != -1 and qe > qs:
            text = line[qs+1:qe].strip()
            if text:
                txt_translations[text] = translate_string(text)

    # Read and decrypt BMD
    with open(bmd_path, 'rb') as f:
        raw = bytearray(f.read())

    decrypted = bytearray(xor_transform(raw, len(raw)))

    # Find strings and translate
    strings = find_strings(bytes(decrypted))
    patched = 0
    for start, end, s in strings:
        translated = translate_string(s)
        if translated != s:
            old_raw = bytes(decrypted[start:end])
            old_len = len(old_raw.rstrip(b'\x00'))
            new_bytes = translated.encode('gbk', errors='replace')
            if len(new_bytes) <= old_len:
                padding = b'\x00' * (old_len - len(new_bytes))
                decrypted[start:start+old_len] = new_bytes + padding
                patched += 1

    if patched > 0:
        encrypted = xor_transform(bytes(decrypted), len(raw))
        with open(bmd_path, 'wb') as f:
            f.write(encrypted)
    print(f'  Patched BMD strings: {patched}')


def translate_bmd_direct(bmd_path):
    """Translate strings directly in a BMD file"""
    name = os.path.basename(bmd_path)
    print(f'\n[{name}]')

    with open(bmd_path, 'rb') as f:
        raw = f.read()

    decrypted = bytearray(xor_transform(raw, len(raw)))
    strings = find_strings(bytes(decrypted))

    vn_count = sum(1 for _, _, s in strings if has_vn_chars(s))
    print(f'  Strings: {len(strings)} (VN: {vn_count})')

    if vn_count == 0 and not any('SOLAR' in s for _, _, s in strings):
        print(f'  -> Skip')
        return

    patched = 0
    for start, end, s in strings:
        if not has_vn_chars(s) and not has_only_ascii(s):
            continue
        translated = translate_string(s)
        if translated == s:
            continue
        old_raw = bytes(decrypted[start:end])
        old_len = len(old_raw.rstrip(b'\x00'))
        new_bytes = translated.encode('gbk', errors='replace')
        if len(new_bytes) <= old_len:
            padding = b'\x00' * (old_len - len(new_bytes))
            decrypted[start:start+old_len] = new_bytes + padding
            patched += 1

    if patched > 0:
        encrypted = xor_transform(bytes(decrypted), len(raw))
        with open(bmd_path, 'wb') as f:
            f.write(encrypted)

    print(f'  Patched: {patched}')


